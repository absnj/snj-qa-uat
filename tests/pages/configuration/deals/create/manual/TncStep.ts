import type { Page, Locator } from '@playwright/test';
import { expect } from '@playwright/test';
import { ConfigBasePage } from '@pages/configuration/ConfigBasePage';
import { PreviewStep } from './PreviewStep';

type TermsData = {
    terms?: string;
    resetToAutoGenerated?: boolean;
};

export class TncStep extends ConfigBasePage {
    private readonly pageTitle: Locator;
    private readonly termsEditor: Locator;
    private readonly resetButton: Locator;
    private readonly nextButton: Locator;

    constructor(page: Page) {
        super(page);
        this.pageTitle = this.page.locator('form').getByText('Terms & Conditions');
        this.termsEditor = this.page.locator('.tiptap');
        this.resetButton = this.page.getByRole('button', { name: 'Reset to Auto-generated' });
        this.nextButton = this.page.getByRole('button', { name: 'Next', exact: true });
    }

    override async waitForReady(): Promise<void> {
        await super.waitForReady();
        await expect(this.pageTitle).toBeVisible();
    }

    async fill(data: TermsData): Promise<void> {
        if (data.resetToAutoGenerated) {
            await this.resetTermsAndConditions();
        }

        if (data.terms !== undefined) {
            await this.fillTermsAndConditions(data.terms);
        }
    }

    async next(): Promise<PreviewStep> {
        await this.nextButton.click();
        return new PreviewStep(this.page);
    }

    async clearTermsAndConditions(): Promise<void> {
        await this.termsEditor.click();
        await this.page.keyboard.press('Meta+a');
        await this.page.keyboard.press('Backspace');
    }

    async resetTermsAndConditions(): Promise<void> {
        await this.resetButton.click();
    }

    private async fillTermsAndConditions(value: string): Promise<void> {
        await this.termsEditor.click();
        await this.termsEditor.fill(value);
    }
}
